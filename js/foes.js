function instantiateMob(enemy, tier, round) {
  return {
    ...enemy,
    round,
    kind: "mob",
    tier: tier.index,
    tierId: tier.id,
    tierName: tier.name,
    field: tier.field,
    fieldName: tier.fieldName,
    fieldText: tier.fieldText,
    color: tier.color,
    deep: tier.deep,
    ink: tier.ink,
    banner: `${tier.fieldName.toUpperCase()} · ${tier.fieldText}`,
    mechanic: null,
  };
}

function instantiateBoss(boss, round) {
  return {
    ...boss,
    round,
    kind: "boss",
    tier: null,
    tierName: "Boss",
    field: "none",
    ability: null,
  };
}

export function buildSeason(rng) {
  const rounds = [];
  let lastId = "";
  for (let round = 1; round <= 30; round++) {
    if (isBossRound(round)) {
      rounds.push(instantiateBoss(BOSSES[round / 5 - 1], round));
      lastId = "";
      continue;
    }
    const tier = TIERS[tierIndexForRound(round)];
    let pool = tier.enemies.filter((e) => e.id !== lastId);
    if (!pool.length) pool = tier.enemies;
    const enemy = pool[Math.floor(rng() * pool.length)];
    lastId = enemy.id;
    rounds.push(instantiateMob(enemy, tier, round));
  }
  return rounds;
}

export function tierAfterBoss(round) {
  if (!isBossRound(round) || round >= 30) return null;
  return TIERS[tierIndexForRound(round + 1)];
}
