export function tierIndexForRound(round) {
  if (round < 5) return 0;
  if (round < 10) return 1;
  if (round < 15) return 2;
  if (round < 20) return 3;
  if (round < 25) return 4;
  return 5;
}

export function isBossRound(round) {
  return round > 0 && round % 5 === 0;
}

